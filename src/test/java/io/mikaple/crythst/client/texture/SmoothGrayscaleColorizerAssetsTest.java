package io.mikaple.crythst.client.texture;

import org.junit.jupiter.api.Test;

import javax.imageio.ImageIO;
import java.awt.Graphics2D;
import java.awt.image.BufferedImage;
import java.io.IOException;
import java.io.InputStream;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Validates the checked-in comparison assets under
 * {@code assets/crythst/textures/test/color_smooth/}.
 *
 * <p>The PNGs are generated by {@code tools/grayscale_formula_assets.py}. This
 * test re-runs the Java formulas against the same grayscale masks, so the
 * Python port and the Java implementation cannot silently drift apart.</p>
 */
class SmoothGrayscaleColorizerAssetsTest {

    private static final String GRAYSCALE_ROOT = "/assets/crythst/textures/test/grayscale/";
    private static final String SMOOTH_ROOT = "/assets/crythst/textures/test/color_smooth/";

    private static final int CYAN = 0xFF00FFFF;
    private static final int PURPLE = 0xFF8000FF;
    private static final int WHITE = 0xFFFFFFFF;

    private record FormulaCase(String suffix, GrayscaleFormula formula, int bands) {
    }

    private record ColorCase(String name, int argb) {
    }

    private static final List<FormulaCase> FORMULAS = List.of(
            new FormulaCase("legacy", GrayscaleFormula.LEGACY, 4),
            new FormulaCase("smooth", GrayscaleFormula.SMOOTH_RAMP, 4),
            new FormulaCase("vanilla3", GrayscaleFormula.VANILLA_BANDS, 3),
            new FormulaCase("vanilla4", GrayscaleFormula.VANILLA_BANDS, 4),
            new FormulaCase("multiply", GrayscaleFormula.MULTIPLY, 4),
            new FormulaCase("linear_light", GrayscaleFormula.LINEAR_LIGHT, 4)
    );

    private static final List<ColorCase> COLORS = List.of(
            new ColorCase("cyan", CYAN),
            new ColorCase("purple", PURPLE),
            new ColorCase("white", WHITE)
    );

    private static final List<String> MASKS = List.of("sword", "chestplate", "humanoid");

    @Test
    void everyGeneratedImageMatchesTheJavaFormula() throws IOException {
        for (String maskName : MASKS) {
            final BufferedImage mask = load(GRAYSCALE_ROOT + maskName + ".png");
            final int[] source = pixels(mask);

            for (ColorCase color : COLORS) {
                for (FormulaCase formulaCase : FORMULAS) {
                    final String file = SMOOTH_ROOT + maskName + "_" + color.name()
                            + "_" + formulaCase.suffix() + ".png";
                    final BufferedImage actual = load(file);
                    assertEquals(mask.getWidth(), actual.getWidth(), "width of " + file);
                    assertEquals(mask.getHeight(), actual.getHeight(), "height of " + file);

                    final int[] expected = SmoothGrayscaleColorizer.tint(
                            source, color.argb(), formulaCase.formula(), formulaCase.bands());
                    final int[] actualPixels = pixels(actual);
                    final Set<Integer> distinct = new LinkedHashSet<>();

                    for (int i = 0; i < source.length; i++) {
                        final int sourceAlpha = alpha(source[i]);
                        assertEquals(sourceAlpha, alpha(actualPixels[i]),
                                "alpha changed at index " + i + " in " + file);
                        if (sourceAlpha == 0) {
                            continue;
                        }
                        assertEquals(expected[i], actualPixels[i],
                                "pixel differs at index " + i + " in " + file);
                        distinct.add(actualPixels[i] & 0x00FFFFFF);
                    }
                    // A flat white highlight is legitimate for a white primary
                    // with SMOOTH_RAMP (the upper half of the ramp is white), so
                    // only require visible variation for the coloured variants.
                    if (!"white".equals(color.name())) {
                        assertTrue(distinct.size() > 1,
                                "expected shading variation in " + file);
                    }
                }
            }
        }
    }

    @Test
    void legacyAssetsAreBitIdenticalToTheOriginalColorizer() throws IOException {
        for (String maskName : MASKS) {
            final BufferedImage mask = load(GRAYSCALE_ROOT + maskName + ".png");
            final int[] source = pixels(mask);
            for (ColorCase color : COLORS) {
                final String file = SMOOTH_ROOT + maskName + "_" + color.name() + "_legacy.png";
                final BufferedImage actual = load(file);
                final int[] expected = GrayscaleColorizer.tint(source, color.argb());
                final int[] actualPixels = pixels(actual);
                for (int i = 0; i < source.length; i++) {
                    if (alpha(source[i]) == 0) {
                        continue;
                    }
                    assertEquals(expected[i], actualPixels[i],
                            "legacy pixel differs at index " + i + " in " + file);
                }
            }
        }
    }

    @Test
    void comparisonSheetsAndTransferCurvesArePresent() throws IOException {
        for (ColorCase color : COLORS) {
            final BufferedImage sheet = load(
                    SMOOTH_ROOT + "comparison_sheet_" + color.name() + ".png");
            assertEquals(600, sheet.getWidth(), "comparison sheet width");
            assertEquals(1070, sheet.getHeight(), "comparison sheet height");
        }

        final BufferedImage curves = load(SMOOTH_ROOT + "transfer_curves.png");
        assertEquals(622, curves.getWidth(), "transfer curve width");
        assertEquals(258, curves.getHeight(), "transfer curve height");

        final BufferedImage gamma = load(SMOOTH_ROOT + "gamma_comparison.png");
        assertEquals(642, gamma.getWidth(), "gamma sheet width");
        assertEquals(180, gamma.getHeight(), "gamma sheet height");
    }

    private static int[] pixels(BufferedImage image) {
        return image.getRGB(0, 0, image.getWidth(), image.getHeight(),
                null, 0, image.getWidth());
    }

    private static int alpha(int argb) {
        return (argb >>> 24) & 0xFF;
    }

    private static BufferedImage load(String resource) throws IOException {
        try (InputStream stream = SmoothGrayscaleColorizerAssetsTest.class
                .getResourceAsStream(resource)) {
            assertNotNull(stream, "missing classpath resource " + resource);
            final BufferedImage source = ImageIO.read(stream);
            assertNotNull(source, "unreadable PNG " + resource);
            final BufferedImage argb = new BufferedImage(
                    source.getWidth(), source.getHeight(), BufferedImage.TYPE_INT_ARGB);
            final Graphics2D graphics = argb.createGraphics();
            try {
                graphics.drawImage(source, 0, 0, null);
            } finally {
                graphics.dispose();
            }
            return argb;
        }
    }
}
