package io.mikaple.crythst.client.texture;

import org.junit.jupiter.api.Test;

import javax.imageio.ImageIO;
import java.awt.Graphics2D;
import java.awt.image.BufferedImage;
import java.io.IOException;
import java.io.InputStream;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Validates the checked-in vanilla diamond grayscale masks and the tinted
 * outputs in {@code assets/crythst/textures/test/}.
 *
 * <p>The PNGs are generated by {@code tools/grayscale_assets.py}. The expected
 * alpha and luminance checksums below were produced from the vanilla 26.3
 * textures and cross-checked with Java's ImageIO, so this test does not need the
 * Minecraft jar on the test classpath.</p>
 */
class GrayscaleAssetsTest {

    private static final String GRAYSCALE_ROOT = "/assets/crythst/textures/test/grayscale/";
    private static final String COLOR_ROOT = "/assets/crythst/textures/test/color/";
    private static final String CONTACT_SHEET = "/assets/crythst/textures/test/grayscale_contact_sheet.png";

    private static final int CYAN = 0xFF00FFFF;
    private static final int PURPLE = 0xFF8000FF;
    private static final int GOLD = 0xFFFFD700;
    private static final int MAGENTA = 0xFFFF00FF;

    /**
     * @param name      file in the grayscale directory
     * @param width     expected width
     * @param height    expected height
     * @param alphaSum  sum of the alpha channel over every pixel
     * @param covered   number of pixels with {@code alpha > 0}
     * @param graySum   sum of the red channel over covered pixels
     */
    private record Mask(String name, int width, int height,
                        long alphaSum, int covered, long graySum) {
    }

    private static final List<Mask> MASKS = List.of(
            new Mask("sword.png", 16, 16, 21420, 84, 7174),
            new Mask("spear.png", 16, 16, 18870, 74, 7238),
            new Mask("pickaxe.png", 16, 16, 17340, 68, 4768),
            new Mask("axe.png", 16, 16, 15300, 60, 4783),
            new Mask("shovel.png", 16, 16, 13515, 53, 4444),
            new Mask("hoe.png", 16, 16, 13005, 51, 3561),
            new Mask("helmet.png", 16, 16, 19890, 78, 7159),
            new Mask("chestplate.png", 16, 16, 35190, 138, 18255),
            new Mask("leggings.png", 16, 16, 26520, 104, 11024),
            new Mask("boots.png", 16, 16, 22440, 88, 8880),
            new Mask("humanoid.png", 64, 32, 161160, 632, 110435),
            new Mask("humanoid_leggings.png", 64, 32, 71400, 280, 47367),
            // Optional extras used by horse and nautilus armour rendering.
            new Mask("horse_armor.png", 16, 16, 22695, 89, 14330),
            new Mask("nautilus_armor.png", 16, 16, 38760, 152, 22783),
            new Mask("horse_body.png", 64, 64, 305235, 1197, 173065),
            new Mask("nautilus_body.png", 128, 128, 404940, 1588, 254559)
    );

    private record TintCase(String mask, String output, int color) {
    }

    private static final List<TintCase> TINT_CASES = List.of(
            new TintCase("sword.png", "sword_cyan.png", CYAN),
            new TintCase("sword.png", "sword_purple.png", PURPLE),
            new TintCase("sword.png", "sword_gold.png", GOLD),
            new TintCase("chestplate.png", "chestplate_cyan.png", CYAN),
            new TintCase("humanoid.png", "humanoid_cyan.png", CYAN)
    );

    private record OutlineCase(String mask, String output, int primary, int outline) {
    }

    private static final List<OutlineCase> OUTLINE_CASES = List.of(
            new OutlineCase("sword.png",
                    "sword_cyan_outline_magenta.png", CYAN, MAGENTA),
            new OutlineCase("humanoid.png",
                    "humanoid_cyan_outline_magenta.png", CYAN, MAGENTA)
    );

    @Test
    void everyMaskIsStrictlyGrayscaleAndKeepsVanillaAlpha() throws IOException {
        for (Mask mask : MASKS) {
            final BufferedImage image = load(GRAYSCALE_ROOT + mask.name());
            assertEquals(mask.width(), image.getWidth(), "width of " + mask.name());
            assertEquals(mask.height(), image.getHeight(), "height of " + mask.name());

            long alphaSum = 0;
            long graySum = 0;
            int covered = 0;
            for (int y = 0; y < image.getHeight(); y++) {
                for (int x = 0; x < image.getWidth(); x++) {
                    final int argb = image.getRGB(x, y);
                    final int alpha = (argb >>> 24) & 0xFF;
                    final int red = (argb >>> 16) & 0xFF;
                    final int green = (argb >>> 8) & 0xFF;
                    final int blue = argb & 0xFF;

                    alphaSum += alpha;
                    if (alpha > 0) {
                        covered++;
                        graySum += red;
                        // Straight alpha masks: the same value in all channels.
                        assertEquals(red, green,
                                "green differs from red at " + x + "," + y + " in " + mask.name());
                        assertEquals(red, blue,
                                "blue differs from red at " + x + "," + y + " in " + mask.name());
                    }
                }
            }

            assertEquals(mask.alphaSum(), alphaSum, "alpha checksum of " + mask.name());
            assertEquals(mask.covered(), covered, "covered pixel count of " + mask.name());
            assertEquals(mask.graySum(), graySum, "BT.601 luminance checksum of " + mask.name());
            // The source textures have transparent padding; a fully opaque mask
            // would mean alpha was lost during conversion.
            assertTrue(covered < mask.width() * mask.height(),
                    "expected some transparent pixels in " + mask.name());
        }
    }

    @Test
    void bt601LuminanceMatchesKnownSourcePixels() throws IOException {
        // Values converted from the vanilla diamond textures with
        // (299*r + 587*g + 114*b + 500) / 1000, integer division.
        final BufferedImage sword = load(GRAYSCALE_ROOT + "sword.png");
        assertGray(sword, 14, 0, 47, 0xFF);
        assertGray(sword, 13, 1, 225, 0xFF);
        assertGray(sword, 15, 1, 28, 0xFF);
        assertGray(sword, 0, 0, 0, 0x00);

        final BufferedImage chestplate = load(GRAYSCALE_ROOT + "chestplate.png");
        assertGray(chestplate, 1, 2, 47, 0xFF);

        final BufferedImage humanoid = load(GRAYSCALE_ROOT + "humanoid.png");
        assertGray(humanoid, 8, 0, 158, 0xFF);
        assertGray(humanoid, 9, 0, 149, 0xFF);
    }

    @Test
    void tintedOutputsMatchTheColorizer() throws IOException {
        for (TintCase tintCase : TINT_CASES) {
            final BufferedImage mask = load(GRAYSCALE_ROOT + tintCase.mask());
            final BufferedImage actual = load(COLOR_ROOT + tintCase.output());
            assertEquals(mask.getWidth(), actual.getWidth(), "width of " + tintCase.output());
            assertEquals(mask.getHeight(), actual.getHeight(), "height of " + tintCase.output());

            final int[] source = pixels(mask);
            final int[] expected = GrayscaleColorizer.tint(source, tintCase.color());
            final int[] actualPixels = pixels(actual);

            final Set<Integer> distinct = new LinkedHashSet<>();
            for (int i = 0; i < source.length; i++) {
                assertEquals(alpha(source[i]), alpha(actualPixels[i]),
                        "alpha changed at index " + i + " in " + tintCase.output());
                if (alpha(source[i]) == 0) {
                    assertEquals(0, alpha(actualPixels[i]),
                            "transparent source became visible in " + tintCase.output());
                    continue;
                }
                assertEquals(expected[i], actualPixels[i],
                        "tinted pixel differs at index " + i + " in " + tintCase.output());
                distinct.add(actualPixels[i] & 0x00FFFFFF);
            }

            // A flat image would pass an alpha test but is clearly not tinted.
            assertTrue(distinct.size() > 1,
                    "expected shading variation in " + tintCase.output());
        }
    }

    @Test
    void outlineOutputsMatchTheTwoColourPass() throws IOException {
        for (OutlineCase outlineCase : OUTLINE_CASES) {
            final BufferedImage mask = load(GRAYSCALE_ROOT + outlineCase.mask());
            final BufferedImage actual = load(COLOR_ROOT + outlineCase.output());
            final int[] source = pixels(mask);
            final int[] actualPixels = pixels(actual);

            final int[] expected = GrayscaleColorizer.tintWithOutline(
                    source, mask.getWidth(), mask.getHeight(),
                    outlineCase.primary(), outlineCase.outline(),
                    OutlineMask.Mode.FOUR_NEIGHBOURS, 0);

            boolean sawOutlinePixel = false;
            final int[] plain = GrayscaleColorizer.tint(source, outlineCase.primary());
            for (int i = 0; i < source.length; i++) {
                assertEquals(alpha(source[i]), alpha(actualPixels[i]),
                        "alpha changed at index " + i + " in " + outlineCase.output());
                if (alpha(source[i]) == 0) {
                    continue;
                }
                assertEquals(expected[i], actualPixels[i],
                        "outline pixel differs at index " + i + " in " + outlineCase.output());
                if (actualPixels[i] != plain[i]) {
                    sawOutlinePixel = true;
                }
            }
            assertTrue(sawOutlinePixel,
                    "outline colour was never applied in " + outlineCase.output());
        }
    }

    @Test
    void documentedColorEndpointsMatchTheColorizer() {
        // This mirrors docs/grayscale-assets.md. Each row is the RGB output for
        // one mask value h, for the three colours used by the test assets.
        assertColor(CYAN, 0, 0, 0, 0);
        assertColor(CYAN, 64, 0, 128, 128);
        assertColor(CYAN, 128, 1, 255, 255);
        assertColor(CYAN, 192, 65, 191, 191);
        assertColor(CYAN, 255, 255, 255, 255);

        assertColor(PURPLE, 64, 64, 0, 128);
        assertColor(PURPLE, 128, 128, 1, 255);
        assertColor(PURPLE, 192, 128, 65, 191);
        assertColor(PURPLE, 255, 255, 255, 255);

        assertColor(GOLD, 64, 128, 108, 0);
        assertColor(GOLD, 128, 255, 215, 1);
        assertColor(GOLD, 192, 191, 171, 65);
        assertColor(GOLD, 255, 255, 255, 255);
    }

    @Test
    void contactSheetIsPresentAndReadable() throws IOException {
        final BufferedImage sheet = load(CONTACT_SHEET);
        assertEquals(600, sheet.getWidth(), "contact sheet width");
        assertEquals(600, sheet.getHeight(), "contact sheet height");
    }

    private static void assertColor(int color, int gray, int red, int green, int blue) {
        assertEquals(red, GrayscaleColorizer.tintChannel((color >>> 16) & 0xFF, gray),
                "red for " + hex(color) + " at h=" + gray);
        assertEquals(green, GrayscaleColorizer.tintChannel((color >>> 8) & 0xFF, gray),
                "green for " + hex(color) + " at h=" + gray);
        assertEquals(blue, GrayscaleColorizer.tintChannel(color & 0xFF, gray),
                "blue for " + hex(color) + " at h=" + gray);
    }

    private static void assertGray(BufferedImage image, int x, int y, int gray, int alpha) {
        final int argb = image.getRGB(x, y);
        assertEquals(gray, (argb >>> 16) & 0xFF, "red at " + x + "," + y);
        assertEquals(gray, (argb >>> 8) & 0xFF, "green at " + x + "," + y);
        assertEquals(gray, argb & 0xFF, "blue at " + x + "," + y);
        assertEquals(alpha, (argb >>> 24) & 0xFF, "alpha at " + x + "," + y);
    }

    private static int[] pixels(BufferedImage image) {
        return image.getRGB(0, 0, image.getWidth(), image.getHeight(),
                null, 0, image.getWidth());
    }

    private static int alpha(int argb) {
        return (argb >>> 24) & 0xFF;
    }

    private static String hex(int color) {
        return String.format("#%08X", color);
    }

    private static BufferedImage load(String resource) throws IOException {
        try (InputStream stream = GrayscaleAssetsTest.class.getResourceAsStream(resource)) {
            assertNotNull(stream, "missing classpath resource " + resource);
            final BufferedImage source = ImageIO.read(stream);
            assertNotNull(source, "unreadable PNG " + resource);
            // Normalise to ARGB so getRGB returns standard 0xAARRGGBB values.
            final BufferedImage argb = new BufferedImage(
                    source.getWidth(), source.getHeight(), BufferedImage.TYPE_INT_ARGB);
            final Graphics2D graphics = argb.createGraphics();
            try {
                graphics.drawImage(source, 0, 0, null);
            } finally {
                graphics.dispose();
            }
            return argb;
        }
    }

    private GrayscaleAssetsTest() {
    }
}
